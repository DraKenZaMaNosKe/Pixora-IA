def make_layer(src_name: str, out_name: str, paste_box=None,
               target=(TARGET_W, TARGET_H)):
    """Place src into TARGET-sized transparent canvas.
    paste_box=None → cover-fit centered. paste_box=(x,y,w,h) → resize+pos."""
    src = Image.open(SRC / src_name).convert("RGBA")
    canvas = Image.new("RGBA", target, (0, 0, 0, 0))
    if paste_box is None:
        sr, tr = src.width / src.height, target[0] / target[1]
        if sr > tr:
            new_h = target[1]
            new_w = int(src.width * (new_h / src.height))
        else:
            new_w = target[0]
            new_h = int(src.height * (new_w / src.width))
        resized = src.resize((new_w, new_h), Image.LANCZOS)
        canvas.paste(resized, ((target[0] - new_w) // 2,
                               (target[1] - new_h) // 2), resized)
    else:
        x, y, w, h = paste_box
        canvas.paste(src.resize((w, h), Image.LANCZOS), (x, y),
                     src.resize((w, h), Image.LANCZOS))
    canvas.save(OUT / out_name, "WEBP", quality=88, method=6)
    print(f"  {{out_name}}: {{(OUT / out_name).stat().st_size // 1024}} KB")


def build_composite(layer_filenames: list[str]):
    """Composite layers (in order) into stable {{ID}}.webp + preview."""
    composite = Image.open(OUT / layer_filenames[0]).convert("RGBA")
    for fn in layer_filenames[1:]:
        composite = Image.alpha_composite(composite,
            Image.open(OUT / fn).convert("RGBA"))
    rgb = Image.new("RGB", composite.size, (0, 0, 0))
    rgb.paste(composite, mask=composite.split()[3])
    # STABLE NAMES — required for canvas_scene auto-upgrade. Do NOT version.
    rgb.save(OUT / f"{{ID}}.webp", "WEBP", quality=85, method=6)
    preview = rgb.copy()
    preview.thumbnail((540, 1170), Image.LANCZOS)
    preview.save(OUT / f"{{ID}}_preview.webp", "WEBP", quality=78, method=6)
    print(f"  composite + preview written (stable names, no version suffix)")


def upload(local: Path, bucket: str, key: str, ctype: str):
    url = f"{{URL}}/storage/v1/object/{{bucket}}/{{urllib.parse.quote(key)}}"
    body = local.read_bytes()
    req = urllib.request.Request(
        url, data=body,
        headers={{**H_AUTH, "Content-Type": ctype, "x-upsert": "true"}},
        method="POST")
    try:
        urllib.request.urlopen(req).read()
        print(f"  uploaded {{bucket}}/{{key}} ({{len(body)//1024}} KB)")
    except urllib.error.HTTPError as e:
        print(f"  FAIL: {{e.code}} {{e.read().decode()[:200]}}")


def write_scene_spec(spec: dict):
    spec_path = OUT / f"{{ID}}.json"
    spec_path.write_text(json.dumps(spec, indent=2, ensure_ascii=False),
                         encoding="utf-8")
    upload(spec_path, "wallpaper-scenes", f"{{ID}}.json", "application/json")


def patch_catalog_index(category: str, title_es: str, title_en: str,
                        tags: list[str]):
    public = f"{{URL}}/storage/v1/object/public/wallpaper-images/catalog_index.json"
    idx = json.loads(urllib.request.urlopen(public).read())
    idx["items"] = [it for it in idx["items"] if it.get("id") != ID]
    entry = {{
        "id": ID,
        "type": "canvas_scene",
        "schema": 1,
        "title": {{"en": title_en, "es": title_es}},
        "preview_url": f"{{URL}}/storage/v1/object/public/wallpaper-images/{{ID}}_preview.webp",
        "tags": tags,
        "category": category,
        "featured": True,
        "spec_url": f"{{URL}}/storage/v1/object/public/wallpaper-scenes/{{ID}}.json",
    }}
    # PREPEND so newest entries appear FIRST in the 3D tab listing.
    idx["items"].insert(0, entry)
    idx["version"] = idx.get("version", 0) + 1
    tmp = OUT / "catalog_index.json"
    tmp.write_text(json.dumps(idx, indent=2, ensure_ascii=False),
                   encoding="utf-8")
    print(f"  catalog v{{idx['version']}} ({{len(idx['items'])}} items)")
    upload(tmp, "wallpaper-images", "catalog_index.json", "application/json")


