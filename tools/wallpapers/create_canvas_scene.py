    p.add_argument("scene_id", help="snake_case scene id, e.g. mario_nes_brinca")
    p.add_argument("--src", default=r"C:/Users/lalo/Desktop/wallPapers_repo/nuevos",
                   help="folder with source PNGs")
    args = p.parse_args()

    if not args.scene_id.replace("_", "").isalnum():
        sys.exit(f"Invalid scene_id: {args.scene_id} (only [a-z0-9_])")

    out_dir = Path(__file__).parent / f"_tmp_{args.scene_id}"
    out_dir.mkdir(exist_ok=True)
    out_file = out_dir / "build_and_upload.py"
    if out_file.exists():
        ans = input(f"{out_file} exists. Overwrite? [y/N] ")
        if ans.lower() != "y":
            sys.exit("aborted")

    content = TEMPLATE.format(scene_id=args.scene_id, src_dir=args.src)
